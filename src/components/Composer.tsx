import { useEffect, useRef, useState } from "react";
import { ArrowUp, Square, CornerDownLeft, StopCircle } from "lucide-react";

interface Props {
  value: string;
  onChange: (v: string) => void;
  onSubmit: () => void;
  onStop: () => void;
  streaming: boolean;
  modelName: string;
  disabled?: boolean;
}

const MAX = 8000;

export function Composer({
  value,
  onChange,
  onSubmit,
  onStop,
  streaming,
  modelName,
  disabled,
}: Props) {
  const areaRef = useRef<HTMLTextAreaElement>(null);
  const [focused, setFocused] = useState(false);

  // auto-grow
  useEffect(() => {
    const el = areaRef.current;
    if (!el) return;
    el.style.height = "auto";
    el.style.height = `${Math.min(el.scrollHeight, 220)}px`;
  }, [value]);

  useEffect(() => {
    if (!streaming) areaRef.current?.focus();
  }, [streaming]);

  const submit = () => {
    if (streaming || disabled) return;
    if (!value.trim()) return;
    onSubmit();
  };

  return (
    <div className="composer-wrap">
      <div className="composer" data-focused={focused}>
        <textarea
          ref={areaRef}
          value={value}
          rows={1}
          maxLength={MAX}
          placeholder={`Message ${modelName}…`}
          onChange={(e) => onChange(e.target.value)}
          onFocus={() => setFocused(true)}
          onBlur={() => setFocused(false)}
          onKeyDown={(e) => {
            if (e.key === "Enter" && !e.shiftKey && !e.nativeEvent.isComposing) {
              e.preventDefault();
              submit();
            }
          }}
          aria-label="Message"
        />
        <div className="composer__bar">
          <span className="composer__chip" title="Messages are sent to Pollinations">
            <StopCircle size={13} />
            Keyless
          </span>
          <span className="composer__chip" title="Enter sends, Shift+Enter adds a line">
            <CornerDownLeft size={13} />
            Enter to send
          </span>
          <span className="composer__count">
            {value.length > MAX * 0.8 ? `${value.length}/${MAX}` : ""}
          </span>
          {streaming ? (
            <button
              type="button"
              className="send send--stop"
              onClick={onStop}
              title="Stop generating"
              aria-label="Stop generating"
            >
              <Square size={13} fill="currentColor" />
            </button>
          ) : (
            <button
              type="button"
              className="send"
              onClick={submit}
              disabled={!value.trim() || disabled}
              title="Send (Enter)"
              aria-label="Send message"
            >
              <ArrowUp size={17} />
            </button>
          )}
        </div>
      </div>
      <p className="composer__legal">
        Powered by <a href="https://pollinations.ai" target="_blank" rel="noreferrer">Pollinations.ai</a>
        {" "}· responses are generated by third-party models and may be inaccurate.
      </p>
    </div>
  );
}
